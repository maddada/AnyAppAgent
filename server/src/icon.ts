function hslToRgb(h: number, s: number, l: number): [number, number, number] {
  const a = s * Math.min(l, 1 - l);
  const f = (n: number) => {
    const k = (n + h / 30) % 12;
    return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1))));
  };
  return [f(0), f(8), f(4)];
}

export function iconColor(name: string): [number, number, number] {
  const hash = createHash("sha256").update(name.trim().toLowerCase()).digest();
  const hue = ((hash[0] << 8) | hash[1]) % 360;
  return hslToRgb(hue, 0.55, 0.45);
}

function chunk(type: string, data: Buffer): Buffer {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body) >>> 0);
  return Buffer.concat([length, body, crc]);
}

export function placeholderIconPng(name: string, size = 192): Buffer {
  const letter = [...name.toUpperCase()].find((c) => FONT[c] !== undefined) ?? "•";
  const glyph = FONT[letter];
  const [r, g, b] = iconColor(name);
  const scale = Math.floor(size / 12);
  const gw = 5 * scale;
  const gh = 7 * scale;
  const ox = Math.floor((size - gw) / 2);
  const oy = Math.floor((size - gh) / 2);
  const raw = Buffer.alloc((size * 3 + 1) * size);
  for (let y = 0; y < size; y++) {
    const row = y * (size * 3 + 1);
    raw[row] = 0;
    for (let x = 0; x < size; x++) {
      const gx = Math.floor((x - ox) / scale);
      const gy = Math.floor((y - oy) / scale);
      const on = x >= ox && y >= oy && gx < 5 && gy < 7 && glyph[gy][gx] === "1";
      const p = row + 1 + x * 3;
      raw[p] = on ? 255 : r;
      raw[p + 1] = on ? 255 : g;
      raw[p + 2] = on ? 255 : b;
    }
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8;
  header[9] = 2;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
